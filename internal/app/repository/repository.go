type LoadToCalc struct {
	Load Load
	Area int
}

type CalcPage struct {
	RoomType    string
	TotalLoadKg int
	Loads       []LoadToCalc
}

var calcPages = map[int]CalcPage{
	1: {
		RoomType:    "Жилое помещение",
		TotalLoadKg: 29650,
		Loads:       []LoadToCalc{{Load: loads[0], Area: 50}, {Load: loads[1], Area: 30}, {Load: loads[2], Area: 20}},
	},
}

func (r *Repository) GetLoads() ([]Load, error) {
	if len(loads) == 0 {
		return nil, fmt.Errorf("массив пустой")
	}
	return loads, nil
}

func (r *Repository) GetLoad(id int) (Load, error) {
	for _, load := range loads {
		if load.LoadID == id {
			return load, nil
		}
	}
	return Load{}, fmt.Errorf("нагрузка не найдена")
}

func (r *Repository) GetLoadsByTitle(title string) ([]Load, error) {
	t := strings.ToLower(title)
	var result []Load
	for _, load := range loads {
		if strings.Contains(strings.ToLower(load.LoadTitle), t) {
			result = append(result, load)
		}
	}
	return result, nil
}

func (r *Repository) GetCalcPage(id int) (CalcPage, error) {
	if p, ok := calcPages[id]; ok {
		return p, nil
	}
	return CalcPage{}, fmt.Errorf("calc page not found")
}
